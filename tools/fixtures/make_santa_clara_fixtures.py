def write_facility_geoparquet(curated: list[tuple[object, float | None, float | None]], path: Path) -> None:
    recs, geoms = [], []
    for fac, lat, lon in curated:
        recs.append(facility_columns(fac))  # type: ignore[arg-type]
        geoms.append(shapely.to_wkb(shapely.Point(lon, lat)) if lat is not None else None)
    cols = ["facility_id", "gers_id", "kind", "licensed_capacity", "status", "location_precision", "h3_r8"]
    tail = ["release_id", "method_ver", "build_id", "license_class"]
    types = {"licensed_capacity": pa.int32()}  # ADR-002: INTEGER; everything else VARCHAR
    table = pa.table(
        {
            **{c: pa.array([r[c] for r in recs], types.get(c, pa.string())) for c in cols},
            "geom": pa.array(geoms, pa.binary()),
            **{c: pa.array([r[c] for r in recs], pa.string()) for c in tail},
        }
    )
    geo = {
        "version": "1.1.0",
        "primary_column": "geom",
        "columns": {"geom": {"encoding": "WKB", "geometry_types": ["Point"]}},
    }  # CRS omitted = OGC:CRS84
    table = table.replace_schema_metadata({b"geo": json.dumps(geo).encode()})
    pq.write_table(table, path)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


