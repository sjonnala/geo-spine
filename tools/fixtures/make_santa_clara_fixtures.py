def _km_to_lonlat(x_km: float, y_km: float, lat0: float, lon0: float) -> tuple[float, float]:
    dlat = y_km / 110.574
    dlon = x_km / (111.320 * math.cos(math.radians(lat0)))
    return round(lon0 + dlon, 6), round(lat0 + dlat, 6)


def _reach_km(theta: float, scale: float) -> float:
    # Long reach east-west (arterials and an expressway), shorter south, and a straight
    # "barrier" edge to the north (rail line / creek with no crossing in this toy network).
    r = (2.2 + 2.8 * math.cos(theta) ** 2) * scale
    if math.sin(theta) > 0:
        r = min(r, 1.4 * scale / max(math.sin(theta), 1e-6))
    return r


def make_isochrone() -> dict[str, object]:
    feats = []
    for minutes in (15, 10, 5):  # Valhalla lists contours largest first
        scale = minutes / 15
        ring = [
            _km_to_lonlat(
                _reach_km(t, scale) * math.cos(t), _reach_km(t, scale) * math.sin(t), ORIGIN_LAT, ORIGIN_LON
            )
            for t in (2 * math.pi * i / 72 for i in range(72))
        ]
        ring.append(ring[0])
        feats.append(
            {
                "type": "Feature",
                "properties": {"contour": minutes, "metric": "time", "fixture": "synthetic"},
                "geometry": {"type": "Polygon", "coordinates": [[list(p) for p in ring]]},
            }
        )
    lat, lon = h3.cell_to_latlng(ORIGIN)
    return {
        "type": "FeatureCollection",
        "_fixture_note": SYNTHETIC_NOTE,
        "_request": {
            "locations": [{"lat": round(lat, 6), "lon": round(lon, 6)}],
            "costing": "auto",
            "contours": [{"time": 5}, {"time": 10}, {"time": 15}],
            "polygons": True,
        },
        "features": feats,
    }


def make_children(rng: random.Random) -> list[dict[str, object]]:
    o = h3.cell_to_latlng(ORIGIN)
    rows = []
    for c in sorted(h3.grid_disk(ORIGIN, 12)):
        d_km = h3.great_circle_distance(o, h3.cell_to_latlng(c), unit="km")
        n = round(40 + 60 * math.exp(-(d_km**2) / (2 * 3.0**2)) + rng.randint(0, 20))
        rows.append(
            {
                "h3_r8": c,
                "children_0_5": n,
                "release_id": REL.acs,
                "method_ver": "0.1.0",
                "build_id": BUILD_ID,
                "license_class": "public_domain",
            }
        )
    return rows


